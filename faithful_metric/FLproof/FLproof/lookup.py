"""Look up a dependency recorded by tactic-deps.

Every `dependency` entry of a checkpoint is a pair [name, location]. This module
answers "what is it?":

    lookup(name, location)                      -> the declaration: kind, statement, source text
    checkpoints(name, location, expand=False)   -> same as lookup (not decomposed)
    checkpoints(name, location, expand=True)    -> the declaration's proof as checkpoints

Command line (run from the FLproof project directory):

    python3 FLproof/lookup.py Even .lake/packages/mathlib/Mathlib/Algebra/Group/Even.lean
    python3 FLproof/lookup.py double_add\\' proof_deps.lean --expand

Scope: only Mathlib and files built on it (this project's files) are expanded
into checkpoints. Anything else (Lean core: `Nat.add_comm`, ...) can be looked up
but not expanded.

Running tactic-deps on a file takes a while (a large Mathlib file: minutes), so
results are cached in .lake/deps-cache/, keyed by the file's modification time.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent  # the FLproof project directory
EXE = PROJECT / ".lake" / "build" / "bin" / "tactic-deps"
CACHE = PROJECT / ".lake" / "deps-cache"
MATHLIB = PROJECT / ".lake" / "packages" / "mathlib"


DECL = re.compile(r"^\s*(?:@\[.*\]\s*)?(?:(?:private|protected|noncomputable|nonrec|unsafe|partial)\s+)*"
                  r"(?:def|theorem|lemma|abbrev|structure|class|inductive|instance|opaque|axiom)\b", re.M)


class OutOfScope(Exception):
    """The declaration is outside Mathlib and this project, so it is not expanded."""


def _path(location: str) -> Path:
    p = Path(location)
    return (p if p.is_absolute() else PROJECT / p).resolve()


def _module(path: Path) -> str | None:
    """Module name of a source file in a package or the Lean toolchain, else None."""
    parts = path.parts
    if ".lake" in parts and "packages" in parts:
        i = parts.index("packages")
        rel = parts[i + 2:]  # skip "packages/<package>"
    elif "src" in parts and "lean" in parts and "toolchains" in parts:
        i = len(parts) - 1 - parts[::-1].index("lean")
        rel = parts[i + 1:]
    else:
        return None
    return ".".join(rel)[: -len(".lean")] if rel and rel[-1].endswith(".lean") else None


def in_scope(location: str) -> bool:
    """Mathlib, or a file of this project (outside .lake)."""
    p = _path(location)
    return p.is_relative_to(MATHLIB) or (p.is_relative_to(PROJECT) and ".lake" not in p.relative_to(PROJECT).parts)


def _run(*args: str) -> str:
    if not EXE.exists():
        sys.exit("tactic-deps is not built; run `lake build tactic-deps` in the FLproof directory.")
    r = subprocess.run(["lake", "env", str(EXE), *args], cwd=PROJECT, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"tactic-deps {' '.join(args)} failed:\n{r.stderr.strip()}")
    return r.stdout


def process(location: str) -> dict:
    """tactic-deps on a whole file (cached)."""
    path = _path(location)
    key = hashlib.sha1(f"{path}:{path.stat().st_mtime_ns}".encode()).hexdigest()[:16]
    cached = CACHE / f"{path.stem}-{key}.json"
    if cached.exists():
        return json.loads(cached.read_text(encoding="utf-8"))
    out = _run(str(path.relative_to(PROJECT) if path.is_relative_to(PROJECT) else path))
    CACHE.mkdir(parents=True, exist_ok=True)
    cached.write_text(out, encoding="utf-8")
    return json.loads(out)


def _unit(name: str, location: str) -> tuple[dict, bytes]:
    data = process(location)
    for unit in data["units"]:
        if name in unit["declarations"]:
            return unit, _path(location).read_bytes()
    raise KeyError(f"{name} is not declared in {location}")


def lookup(name: str, location: str) -> dict:
    """The declaration `name` in `location`: kind, statement (if known), source text."""
    path = _path(location)
    module = _module(path)
    if module is None:  # a file of this project: not importable, so process it
        unit, src = _unit(name, location)
        a, b = unit["boundary"]
        return {"name": name, "kind": unit["command"].split(".")[-1], "file": location,
                "source": src[a:b].decode("utf-8")}
    info = json.loads(_run("--decl", name, module))
    lines = path.read_text(encoding="utf-8").splitlines()
    if "startLine" in info:
        start, end = info["startLine"] - 1, info["endLine"]
        if not DECL.search("\n".join(lines[start:end])):
            # Generated by an attribute (e.g. `Even` is made from `IsSquare` by
            # `@[to_additive]`): the position is the attribute, so show the
            # declaration it is attached to as well.
            info["generatedFrom"] = "the declaration below the attribute"
            while end < len(lines) and not DECL.search(lines[end]):
                end += 1
            while end < len(lines) and lines[end].strip():
                end += 1
        info["source"] = "\n".join(lines[start:end])
    info["file"] = location
    return info


def checkpoints(name: str, location: str, expand: bool = False) -> dict | list[dict]:
    """expand=False: the declaration itself (see lookup).
    expand=True: its proof as checkpoints. A proof written as a term (no tactics)
    gives one checkpoint of kind "term" holding the whole proof."""
    if not expand:
        return lookup(name, location)
    if not in_scope(location):
        raise OutOfScope(f"{name} ({location}) is outside Mathlib and this project: recorded, not expanded")
    unit, src = _unit(name, location)
    if unit["checkpoints"]:
        return unit["checkpoints"]
    a, b = unit["boundary"]
    return [{"id": 0, "path": f"{Path(location).name}::{name}/0", "kind": "term",
             "tactic": src[a:b].decode("utf-8"), "goalsBefore": [], "goalsAfter": [],
             "dependency": [], "notationDependency": [], "substeps": [], "auxiliary": []}]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("name")
    ap.add_argument("location", help="the second entry of a dependency pair")
    ap.add_argument("--expand", action="store_true", help="return the proof as checkpoints")
    args = ap.parse_args()
    try:
        result = checkpoints(args.name, args.location, args.expand)
    except (OutOfScope, KeyError, RuntimeError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    print(json.dumps(result, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
